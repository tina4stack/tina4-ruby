# frozen_string_literal: true

# Frond vs the competition -- template rendering throughput (Ruby).
#
# The gap this fills: benchmark_results.json measures only `json` and `list`, and
# carbon_benchmarks.rb measures Frond's template category against ITSELF in four
# languages. Neither has ever timed Frond against the engines it competes with.
#
# Two things this harness does that a naive template benchmark does not:
#
# 1. IT PROVES THE ENGINES DO THE SAME WORK. Every engine renders the same page and the
#    output is compared before anything is timed. Whitespace around block tags
#    legitimately differs between engines, so the comparison collapses whitespace runs --
#    but raw byte lengths are printed too, so a suspicious difference stays visible
#    instead of being normalised away. A mismatch ABORTS. Timing engines that emit
#    different HTML is the most common way a template benchmark lies.
#
# 2. IT MEASURES STEADY STATE, NOT COMPILATION. Each engine's template is compiled ONCE
#    outside the clock, then rendered repeatedly, which is what a real app does per
#    request. ERB and Erubi both compile to Ruby source that is then eval'd into a
#    method; doing that inside the loop would be a strawman, not a benchmark.
#
# Competitors: ERB (stdlib, the baseline every Ruby app already has) and Erubi (the
# faster ERB implementation Rails actually uses). Both evaluate plain Ruby expressions,
# so `'%.2f' %` formatting matches Frond's number_format(2) exactly.
#
# Liquid is deliberately NOT included: it has no 2-decimal formatting filter (`round: 2`
# renders 0.0 as "0", not "0.00"), so including it would need a custom filter and the
# equivalence gate would be comparing Frond against a filter this harness wrote. ERB and
# Erubi are the real competition in Ruby web apps anyway.
#
# Run: bundle exec ruby benchmarks/bench_templates.rb

require "erb"
require "erubi"
require "json"
require "tmpdir"
require "fileutils"

$LOAD_PATH.unshift(File.expand_path("../lib", __dir__))
require "tina4"

# Timed runs continue until this much wall-clock has elapsed...
MIN_SECONDS = 0.25
# ...but never fewer than this many iterations, however fast the engine.
MIN_ITERATIONS = 200

REPORT_PATH = File.join(__dir__, "template_comparison.json")

# 20 rows is a realistic list page, not a microbenchmark of one hole.
def page_data
  {
    "title" => "Benchmark Page",
    "heading" => "Product List",
    "items" => (0...20).map { |i| { "name" => "Product #{i}", "price" => i * 9.99 } },
    "show_footer" => true,
    "footer_text" => "Generated by Tina4 Frond for the template throughput comparison."
  }
end

# Collapse whitespace runs so block-tag indentation differences between engines do not
# register as output differences. Everything else must match exactly.
def normalise(html)
  html.split.join(" ")
end

# Time a render block: p50 and mean ops/sec.
#
# Batched for the same reason the carbon suite batches -- a render is fast enough that
# two clock reads are a measurable fraction of the work, and a mean alone hides a fat
# tail. Setup is outside the clock; only the render is timed.
def measure
  # Warm-up is a LOOP and runs twice: one pass still pays cold costs (autoload, lazily
  # built caches, first compile), and reading a single cold op collapses the batch size
  # to 1, defeating the amortisation.
  calibration_ops = 64
  one = 1e-9
  2.times do
    t0 = Process.clock_gettime(Process::CLOCK_MONOTONIC)
    calibration_ops.times { yield }
    one = [(Process.clock_gettime(Process::CLOCK_MONOTONIC) - t0) / calibration_ops, 1e-9].max
  end

  batch = [[(5e-5 / one).to_i, 1].max, 10_000].min

  batches = []
  iterations = 0
  start = Process.clock_gettime(Process::CLOCK_MONOTONIC)
  loop do
    b0 = Process.clock_gettime(Process::CLOCK_MONOTONIC)
    batch.times { yield }
    batches << (Process.clock_gettime(Process::CLOCK_MONOTONIC) - b0) / batch
    iterations += batch
    elapsed = Process.clock_gettime(Process::CLOCK_MONOTONIC) - start
    break if elapsed >= MIN_SECONDS && iterations >= MIN_ITERATIONS
  end

  batches.sort!
  mid = batches.length / 2
  p50 = batches.length.odd? ? batches[mid] : (batches[mid - 1] + batches[mid]) / 2.0
  mean = batches.sum / batches.length

  {
    "p50_ops_sec" => p50 > 0 ? 1 / p50 : 0,
    "mean_ops_sec" => mean > 0 ? 1 / mean : 0,
    "iterations" => iterations,
    "batches" => batches.length
  }
end

FROND_SOURCE = <<~TPL.freeze
  <!DOCTYPE html>
  <html>
  <head><title>{{ title }}</title></head>
  <body>
  <h1>{{ heading }}</h1>
  <ul>
  {% for item in items %}
  <li class="{{ loop.index is even ? 'even' : 'odd' }}">{{ loop.index }}. {{ item.name|upper }} - ${{ item.price|number_format(2) }}</li>
  {% endfor %}
  </ul>
  {% if show_footer %}
  <footer>{{ footer_text }}</footer>
  {% endif %}
  </body>
  </html>
TPL

# ERB / Erubi share one source: both compile the same <%= %> markers to Ruby.
ERB_SOURCE = <<~TPL.freeze
  <!DOCTYPE html>
  <html>
  <head><title><%= title %></title></head>
  <body>
  <h1><%= heading %></h1>
  <ul>
  <% items.each_with_index do |item, idx| %>
  <li class="<%= (idx + 1).even? ? 'even' : 'odd' %>"><%= idx + 1 %>. <%= item['name'].upcase %> - $<%= '%.2f' % item['price'] %></li>
  <% end %>
  </ul>
  <% if show_footer %>
  <footer><%= footer_text %></footer>
  <% end %>
  </body>
  </html>
TPL

# A plain object whose binding exposes the page data as local-ish methods, so ERB and
# Erubi evaluate against real Ruby state rather than a hash lookup per hole. This is the
# fast, idiomatic way to drive ERB -- being fair to the competitor is the whole point.
class ErbContext
  def initialize(data)
    @data = data
  end

  def title = @data["title"]
  def heading = @data["heading"]
  def items = @data["items"]
  def show_footer = @data["show_footer"]
  def footer_text = @data["footer_text"]

  def context_binding = binding
end

tmp = Dir.mktmpdir("tina4_tpl_bench")
File.write(File.join(tmp, "page.twig"), FROND_SOURCE)

data = page_data
engines = {}

# --- Frond (Tina4, zero dependencies) --------------------------------------------
frond = Tina4::Frond.new(template_dir: tmp)
engines["Frond (Tina4)"] = -> { frond.render("page.twig", data) }

# --- ERB (stdlib) -----------------------------------------------------------------
# Compiled to a method ONCE via def_method, outside the clock. Re-running
# ERB.new(...).result every iteration would recompile Ruby source each time.
erb_context = ErbContext.new(data)
ERB.new(ERB_SOURCE, trim_mode: "-").def_method(ErbContext, "render_erb")
engines["ERB (stdlib)"] = -> { erb_context.render_erb }

# --- Erubi (what Rails uses) -------------------------------------------------------
erubi_src = Erubi::Engine.new(ERB_SOURCE).src
ErbContext.class_eval("def render_erubi; #{erubi_src}; end", __FILE__, __LINE__)
engines["Erubi (Rails)"] = -> { erb_context.render_erubi }

puts
puts "Tina4 Frond vs the competition -- template rendering (Ruby #{RUBY_VERSION})"
puts
puts "  Output equivalence gate"
puts "  #{'-' * 72}"

rendered = engines.transform_values(&:call)

reference = nil
reference_name = ""
mismatch = false
rendered.each do |name, html|
  norm = normalise(html)
  if reference.nil?
    reference = norm
    reference_name = name
    printf("    %-22s %6d bytes raw  (reference)\n", name, html.bytesize)
    next
  end
  same = norm == reference
  printf("    %-22s %6d bytes raw  %s\n", name, html.bytesize, same ? "IDENTICAL" : "MISMATCH")
  next if same

  mismatch = true
  # Show where they diverge. A silent normalise-and-move-on is how a benchmark ends up
  # comparing engines that render different pages.
  at = (0...[norm.length, reference.length].min).find { |i| norm[i] != reference[i] } ||
       [norm.length, reference.length].min
  puts "      first difference at char #{at}:"
  puts "        #{reference_name}: ...#{reference[[0, at - 40].max, 90]}..."
  puts "        #{name}: ...#{norm[[0, at - 40].max, 90]}..."
end

if mismatch
  puts
  puts "  ABORTED: the engines do not render the same page, so any timing below would be"
  puts "  comparing different work. Fix the templates before trusting a number."
  puts
  FileUtils.remove_entry(tmp)
  exit 1
end

puts
puts "  All engines render the same page. Timing is meaningful."
puts

# Report Frond's configuration so the number cannot be dismissed as "you benchmarked
# the wrong path". Ruby's Frond caches TOKENS (@compiled) but has NO AOT compile-to-
# closure layer -- PHP (FrondCompiler) and Python (frond/compiler.py) both do. That
# asymmetry is a real parity gap, and it is the leading explanation for any gap below.
debug_mode = ENV.fetch("TINA4_DEBUG", "").downcase == "true"
has_aot = defined?(Tina4::FrondCompiler) ? "present" : "NOT IMPLEMENTED in Ruby"
puts "  Frond configuration (so the number cannot be dismissed)"
puts "  #{'-' * 72}"
puts "    Token cache (@compiled)        active (production path)"
puts "    AOT compile-to-closure layer   #{has_aot} -- PHP and Python have one"
puts "    TINA4_DEBUG                    #{debug_mode ? 'true (dev: re-reads + re-tokenizes)' : 'not true (production)'}"
puts

printf("  %-22s %13s %13s   %s\n", "Engine", "p50 ops/sec", "mean ops/sec", "samples")
puts "  #{'-' * 72}"

results = {}
engines.each do |name, render|
  m = measure { render.call }
  results[name] = m
  printf("  %-22s %13s %13s   %s\n", name,
         m["p50_ops_sec"].round.to_s.reverse.scan(/\d{1,3}/).join(",").reverse,
         m["mean_ops_sec"].round.to_s.reverse.scan(/\d{1,3}/).join(",").reverse,
         "#{m['iterations']}x#{m['batches']}")
end

frond_p50 = results["Frond (Tina4)"]["p50_ops_sec"]
puts
puts "  Relative to Frond (p50):"
results.each do |name, m|
  next if name == "Frond (Tina4)"

  ratio = m["p50_ops_sec"] > 0 ? frond_p50 / m["p50_ops_sec"] : Float::INFINITY
  printf("    Frond is %.2fx %s than %s\n", ratio >= 1 ? ratio : 1 / ratio,
         ratio >= 1 ? "faster" : "SLOWER", name)
end

File.write(REPORT_PATH, JSON.pretty_generate({
  "language" => "ruby",
  "runtime" => "Ruby #{RUBY_VERSION}",
  "page" => { "items" => 20, "engines" => engines.keys },
  "output_equivalence" => "verified",
  "aot_compile_layer" => has_aot,
  "results" => results
}) + "\n")

puts
puts "  Wrote #{File.basename(REPORT_PATH)}"
puts
puts "  Note: steady-state render only. Every engine's template is compiled ONCE outside"
puts "  the clock, matching how an app serves a page. Cold-start compile cost is a"
puts "  separate question and is NOT measured here."
puts

FileUtils.remove_entry(tmp)
